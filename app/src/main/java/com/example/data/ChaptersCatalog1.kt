object WorldCoords {
    const val VS = 0.125f

    fun m(v: Float): Float = v * VS
    fun m(v: Int): Float = v * VS

    private val areaOffsets = mapOf(
        "start" to (560f to 1256f),
        "crossing" to (560f to 1176f),
        "meadow" to (440f to 1016f),
        "house" to (600f to 856f),
        "campfire" to (480f to 736f),
        "thicket" to (360f to 736f),
        "upstream" to (160f to 696f),
        "cliff" to (120f to 536f),
        "north" to (600f to 536f)
    )

    fun areaX(area: String, x: Float): Float = (x + (areaOffsets[area]?.first ?: 0f)) * VS
    fun areaZ(area: String, z: Float): Float = (z + (areaOffsets[area]?.second ?: 0f)) * VS

    fun crX(x: Float) = areaX("crossing", x)
    fun crZ(z: Float) = areaZ("crossing", z)
    fun mdX(x: Float) = areaX("meadow", x)
    fun mdZ(z: Float) = areaZ("meadow", z)
    fun hoX(x: Float) = areaX("house", x)
    fun hoZ(z: Float) = areaZ("house", z)
    fun tkX(x: Float) = areaX("thicket", x)
    fun tkZ(z: Float) = areaZ("thicket", z)
    fun upaX(x: Float) = areaX("upstream", x)
    fun upaZ(z: Float) = areaZ("upstream", z)
    fun noX(x: Float) = areaX("north", x)
    fun noZ(z: Float) = areaZ("north", z)

    val P_START = ((512 + 560) * VS) to ((920 + 1256) * VS)
    val P_CROSSING = crX(512f) to crZ(728f)
    val P_MEADOW = mdX(400f) to mdZ(592f)
    val P_BENCH = hoX(548f) to hoZ(504f)
    val P_CAMPFIRE = areaX("campfire", 424f) to areaZ("campfire", 352f)
    val P_THICKET = tkX(304f) to tkZ(336f)
    val P_UPSTREAM = upaX(212f) to upaZ(372f)
    val P_CLIFF = areaX("cliff", 200f) to areaZ("cliff", 296f)
    val P_POOL = noX(604f) to noZ(56f)
    val P_CAVE = noX(604f) to noZ(64f)
}

